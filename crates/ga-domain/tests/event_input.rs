use std::{
    error::Error,
    fs::File,
    io::{self, BufRead, BufReader},
};

use ga_domain::event_input::{EventInput, EventSource, EventStatus, InvalidEvent, ValidationMode};
use serde_json::{Value, json};

#[test]
fn only_confirmed_reported_intake_may_omit_medication_values() -> Result<(), InvalidEvent> {
    let raw = br#"{"start":"2026-10-25T02:30:00+02:00","payload":{"type":"medication"}}"#;
    let event = EventInput::from_json(raw, 1024, ValidationMode::NewReport)?;
    assert_eq!(event.source(), EventSource::Manual);
    assert_eq!(event.status(), EventStatus::Confirmed);
    assert!(event.payload().json()["name"].is_null());
    assert!(event.payload().json()["dose"].is_null());
    assert!(event.payload().json()["unit"].is_null());
    let unconfirmed = br#"{"start":"2026-10-25T02:30:00+02:00","status":"needs_confirmation","payload":{"type":"medication"}}"#;
    assert!(matches!(
        EventInput::from_json(unconfirmed, 1024, ValidationMode::NewReport),
        Err(InvalidEvent::MedicationNotReported)
    ));
    Ok(())
}

#[test]
fn repeated_local_time_preserves_distinct_instants_and_coverage() -> Result<(), InvalidEvent> {
    let coverage = br#"{"start":"2026-10-25T02:30:00+02:00","end":"2026-10-25T02:30:00+01:00","payload":{"type":"caffeine_log_complete","description":"Synthetic"}}"#;
    let event = EventInput::from_json(coverage, 2048, ValidationMode::NewReport)?;
    assert_eq!(
        event
            .end()
            .map(|end| end.unix_microseconds() - event.start().unix_microseconds()),
        Some(3_600_000_000)
    );
    assert_eq!(event.timezone(), "Europe/Bratislava");
    Ok(())
}

#[test]
#[ignore = "uses synthetic cases generated by migration/check_event_inputs.py"]
fn event_context_and_timestamps_match_the_pinned_python_model() -> Result<(), Box<dyn Error>> {
    let fixture = std::env::var_os("GA_TEST_EVENT_INPUTS")
        .ok_or_else(|| io::Error::other("Use the generated synthetic event reference"))?;
    let mut inspected = 0;
    let mut mismatches = Vec::new();
    for (line_number, line) in BufReader::new(File::open(fixture)?).lines().enumerate() {
        let case: Value = serde_json::from_str(&line?)?;
        let raw = case["input"]
            .as_str()
            .ok_or_else(|| io::Error::other("Synthetic case lacks input"))?;
        let mode = if case["audited"] == true {
            ValidationMode::AuditedSnapshot
        } else {
            ValidationMode::NewReport
        };
        let result = EventInput::from_json(raw.as_bytes(), 65_536, mode);
        let outcome = result.as_ref().map_or(Value::Null, |event| {
            json!({
                "start": event.start().unix_microseconds(),
                "end": event.end().map(ga_domain::timestamp::StoredInstant::unix_microseconds),
                "timezone": event.timezone(),
                "source": event.source().label(),
                "status": event.status().label(),
                "confidence": event.confidence(),
                "original_text": event.original_text(),
                "payload": event.payload().json(),
            })
        });
        if outcome != case["expected"] {
            mismatches.push((
                line_number + 1,
                raw.chars().take(160).collect::<String>(),
                result.err(),
            ));
        }
        inspected += 1;
    }
    assert!(inspected > 1200);
    assert!(mismatches.is_empty(), "{mismatches:?}");
    Ok(())
}

#[test]
fn provenance_depends_on_the_authenticated_actor_and_preserves_recorded_time()
-> Result<(), Box<dyn Error>> {
    use ga_domain::event_provenance::{EventTopology, InvalidClockUncertainty};
    let raw = br#"{"start":"2026-10-25T02:30:00+02:00","source":"wearable","payload":{"type":"note","description":"Synthetic"}}"#;
    let event = EventInput::from_json(raw, 2048, ValidationMode::NewReport)?;
    let recorded = "2026-11-01T12:00:00Z".parse()?;
    let api = event.provenance(Some("api"), EventTopology::Flexible, recorded, None)?;
    assert_eq!(
        (api.assertion_kind, api.producer, api.transport, api.author),
        ("user_report", "owner", Some("api"), Some("owner"))
    );
    assert_eq!(
        (api.recorded_at, api.ingested_at, api.time_precision),
        (recorded, recorded, "instant")
    );
    assert!(matches!(
        event.provenance(Some("api"), EventTopology::Point, recorded, Some(10)),
        Err(InvalidClockUncertainty)
    ));
    let device = event.provenance(
        Some("wearable:synthetic"),
        EventTopology::Point,
        recorded,
        Some(10),
    )?;
    assert_eq!(
        (
            device.assertion_kind,
            device.validation_status,
            device.time_precision
        ),
        ("device_measurement", "trusted", "unknown")
    );
    assert_eq!(device.author, None);
    assert_eq!(device.clock_uncertainty_seconds, Some(10));
    Ok(())
}
