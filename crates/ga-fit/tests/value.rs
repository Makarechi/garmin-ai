use std::{
    error::Error,
    fs::File,
    io::{BufRead, BufReader},
};

use ga_fit::{ByteOrder, FitError, RawFitValue, WireField};
use serde_json::{Value, json};

#[test]
fn interprets_unknown_types_and_missing_values_without_overriding_raw_bytes() -> Result<(), FitError>
{
    let mut field = WireField {
        number: 99,
        developer_data_index: None,
        base_type: Some(0x0d),
        bytes: vec![0, 255, 3],
    };
    let decoded = field.decode_native(ByteOrder::Big)?;
    assert!(decoded == Some(("byte", RawFitValue::Bytes(vec![0, 255, 3]))));
    field.base_type = Some(0x02);
    let decoded = field.decode_native(ByteOrder::Big)?;
    assert!(
        decoded
            == Some((
                "uint8",
                RawFitValue::Array(vec![
                    RawFitValue::Unsigned(0),
                    RawFitValue::Invalid,
                    RawFitValue::Unsigned(3),
                ])
            ))
    );
    field.base_type = None;
    field.developer_data_index = Some(2);
    assert!(field.decode_native(ByteOrder::Big)?.is_none());
    assert_eq!(field.bytes, [0, 255, 3]);
    Ok(())
}

#[test]
#[ignore = "uses synthetic cases generated by migration/check_fit_wire_values.py"]
fn native_wire_values_match_fitdecode() -> Result<(), Box<dyn Error>> {
    let path = std::env::var_os("GA_TEST_FIT_VALUES").ok_or("GA_TEST_FIT_VALUES missing")?;
    let mut tested = 0;
    for row in BufReader::new(File::open(path)?).lines() {
        let (wire_type, endian, bytes, expected): (u8, u8, Vec<u8>, Value) =
            serde_json::from_str(&row?)?;
        let order = if endian == 0 {
            ByteOrder::Little
        } else {
            ByteOrder::Big
        };
        let wire = WireField {
            number: 222,
            developer_data_index: None,
            base_type: Some(wire_type),
            bytes,
        };
        let (name, value) = wire.decode_native(order)?.ok_or("missing decoded field")?;
        assert_eq!(json!([name, shape(value)]), expected, "case {}", tested + 1);
        tested += 1;
    }
    assert_eq!(tested, 1080);
    Ok(())
}

fn shape(value: RawFitValue) -> Value {
    match value {
        RawFitValue::Invalid => json!(["invalid"]),
        RawFitValue::Unsigned(value) => json!(["unsigned", value]),
        RawFitValue::Signed(value) => json!(["signed", value]),
        RawFitValue::Float(value) => json!(["float", value.to_bits()]),
        RawFitValue::Text(value) => json!(["text", value]),
        RawFitValue::Bytes(value) => json!(["bytes", value]),
        RawFitValue::Array(value) => {
            json!(["array", value.into_iter().map(shape).collect::<Vec<_>>()])
        }
    }
}
