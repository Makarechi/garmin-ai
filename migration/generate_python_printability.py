"""Generate Rust's Python repr character table with the pinned baseline interpreter."""

import argparse
import unicodedata
from pathlib import Path

UNICODE_VERSION = "17.0.0"


def unprintable_ranges():
    start = None
    for code in range(0x110000):
        if not chr(code).isprintable():
            if start is None:
                start = code
        elif start is not None:
            yield start, code - 1
            start = None
    if start is not None:
        yield start, 0x10FFFF


def generate(path):
    assert unicodedata.unidata_version == UNICODE_VERSION
    ranges = [f"(0x{start:x}, 0x{end:x})," for start, end in unprintable_ranges()]
    lines = [
        "// Generated by migration/generate_python_printability.py.",
        f"// CPython Unicode {UNICODE_VERSION} str.isprintable() ranges.",
        "#[rustfmt::skip]",
        "pub(super) const UNPRINTABLE: &[(u32, u32)] = &[",
        *("    " + " ".join(ranges[index : index + 4]) for index in range(0, len(ranges), 4)),
        "];",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    generate(parser.parse_args().output)
