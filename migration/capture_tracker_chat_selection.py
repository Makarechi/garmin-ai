def unicode_word_ranges(regex_tables=None):
    ranges = []
    first = None
    for code in range(0x110001):
        included = code < 0x110000 and chr(code).isalnum()
        if included and first is None:
            first = code
        elif not included and first is not None:
            ranges.append((first, code - 1))
            first = None
    output = (
        "// Generated by migration/capture_tracker_chat_selection.py from frozen Python.\n"
        + "pub(super) const ALNUM_RANGES: &[(u32,u32)] = &[\n"
        + "".join(f"    (0x{first:x}, 0x{last:x}),\n" for first, last in ranges)
        + "];\n"
    )
    output += "pub(super) const RE_LOWER: &[(u32,u32)] = &[\n"
    for code in range(0x110000):
        lower = _sre.unicode_tolower(code)
        if lower != code:
            output += f"    (0x{code:x},0x{lower:x}),\n"
    output += "];\n"
    output += "pub(super) const RE_EXTRA: &[(u32,u32)] = &[\n"
    for code, others in sorted(_EXTRA_CASES.items()):
        for other in sorted(others):
            output += f"    (0x{code:x},0x{other:x}),\n"
    output += "];\n"
    if regex_tables:
        # Compress the exact frozen set relative to the pinned regex crate's Unicode tables.
        base = set()
        tables = regex_tables.read_text()
        for name in ["LETTER", "NUMBER"]:
            body = tables.split(f"pub const {name}:", 1)[1].split("];", 1)[0]
            for first, last in re.findall(r"\('([^']+)', '([^']+)'\)", body):

                def point(value):
                    return int(value[3:-1], 16) if value.startswith("\\u{") else ord(value)

                base.update(range(point(first), point(last) + 1))
        frozen = {code for first, last in ranges for code in range(first, last + 1)}

        def encoded(points):
            runs = []
            for code in sorted(points):
                if runs and code == runs[-1][1] + 1:
                    runs[-1][1] = code
                else:
                    runs.append([code, code])
            return "".join(f"\\x{{{first:x}}}-\\x{{{last:x}}}" for first, last in runs)

        letters = r"\p{L}\p{N}" + encoded(frozen - base)
        removed = encoded(base - frozen)
        compact = f"[[{letters}]--[{removed}]]" if removed else f"[{letters}]"
        output += f'pub(super) const ALNUM_CLASS: &str = r"{compact}";\n'
    return output


